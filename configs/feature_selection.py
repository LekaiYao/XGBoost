def resolve_feature_selection_experiment(name):
    cfg = deepcopy(FEATURE_SELECTION_EXPERIMENTS[name])
    if cfg.get("retired"):
        raise ValueError("Retired experiment: retained artifacts are read-only; restore archived configuration to rerun")
    if cfg["operation"] not in ("drop1", "add1"):
        raise ValueError("Unsupported feature-selection operation")
    if "/" in name or "\\" in name or not name.startswith("fs_"):
        raise ValueError("Invalid experiment directory name")
    from utils.varsets import infer_varset_from_tag
    expected = f"fs_{infer_varset_from_tag(cfg['baseline'])}_{cfg['operation']}_{cfg['baseline']}"
    if name != expected:
        raise ValueError(f"Experiment name must be {expected}")
    tags = [item["train_tag"] for item in cfg["candidates"]]
    if len(set(tags)) != len(tags) or cfg["baseline"] in tags:
        raise ValueError("Duplicate candidate or baseline included as candidate")
    return cfg


def experiment_for_tag(train_tag):
    owners = [name for name, cfg in FEATURE_SELECTION_EXPERIMENTS.items()
              if any(item["train_tag"] == train_tag for item in cfg["candidates"])]
    if len(owners) > 1:
        raise ValueError(f"Ambiguous experiment ownership for {train_tag}: {owners}")
    if owners:
        if not FEATURE_SELECTION_EXPERIMENTS[owners[0]].get("retired"):
            resolve_feature_selection_experiment(owners[0])
        return owners[0]
    return None
